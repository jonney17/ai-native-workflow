#!/usr/bin/env python3
"""Generate one Copilot custom agent per lane into .github/agents/.

Source of truth stays in skills/ (instructions) and config/agents.yaml (description, tools). The generated
files are committed so Copilot can load them (`copilot --agent wf-planner`, found through --add-dir <root>).

Usage:
  python scripts/build_agents.py            write .github/agents/wf-*.agent.md
  python scripts/build_agents.py --check    exit 1 if a generated file is missing or out of date
"""
import argparse
import sys
from pathlib import Path

sys.dont_write_bytecode = True
try:
    import yaml
except ImportError:
    sys.exit("error: PyYAML is required. Install it with: python -m pip install -r requirements.txt")

ROOT = Path(__file__).resolve().parent.parent

PREAMBLE = """\
You are one lane of an AI-native delivery workflow. Your role is fixed by this file; the task message only
says which work item to do it for.

How to read this file:
- The task message gives the workflow root (`root`) and the run folder (`run_dir`). Every relative path below
  (`skills/...`, `config/...`, `overlay/...`, `tickets/...`) is relative to `root`, even when your working directory is a repo.
- You cannot ask questions. If you are blocked, append `question_raised` to `events.log` and stop.
- Stop when your lane's artifacts are written.
"""


def render(lane, spec, prefix):
    common = (ROOT / "skills" / "_common.md").read_text(encoding="utf-8").strip()
    own = (ROOT / "skills" / lane / "instructions.md").read_text(encoding="utf-8").strip()
    fm = {"name": f"{prefix}{lane}", "description": spec["description"], "tools": list(spec.get("tools") or [])}
    if spec.get("model"):
        fm["model"] = spec["model"]
    head = yaml.safe_dump(fm, sort_keys=False, default_flow_style=None, width=1000).strip()
    return (f"---\n{head}\n---\n"
            f"<!-- GENERATED by scripts/build_agents.py from skills/_common.md, skills/{lane}/instructions.md and config/agents.yaml. "
            f"Edit those, then rebuild. -->\n\n{PREAMBLE}\n---\n\n{common}\n\n---\n\n{own}\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    cfg = yaml.safe_load((ROOT / "config" / "agents.yaml").read_text(encoding="utf-8"))
    prefix = cfg.get("prefix", "wf-")
    out = ROOT / ".github" / "agents"
    stale = []
    for lane, spec in (cfg.get("lanes") or {}).items():
        text = render(lane, spec, prefix)
        path = out / f"{prefix}{lane}.agent.md"
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8").replace("\r\n", "\n") != text:
                stale.append(path.name)
            continue
        out.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(ROOT).as_posix()}")
    if args.check:
        if stale:
            sys.exit("out of date: " + ", ".join(stale) + "\nrun: python scripts/build_agents.py")
        print("agents are up to date")


if __name__ == "__main__":
    main()
